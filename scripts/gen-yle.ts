import { loadEnvFile } from "node:process";
loadEnvFile(".env");

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { generatePracticeSet } from "../src/lib/yle/generate";
import type { ItemKind, PracticeSet } from "../src/lib/yle/items";
import { levelBySlug } from "../src/lib/yle/syllabus";

/**
 * Generates YLE practice sets into `content/yle-generated.ts`.
 *
 *   npm run gen:yle                 # two sets for every part below
 *   npm run gen:yle -- --each 4     # four each
 *   npm run gen:yle -- flyers       # one level only
 *
 * Generated sets live in their own file, separate from the hand-authored ones
 * in `yle-practice.ts`, so a regeneration can never overwrite work a person
 * did — and so it is always obvious which is which when reviewing.
 *
 * Every set is validated against the real part before it is kept: right number
 * of questions, one correct option, gaps matching questions, answers present
 * in the word box. A set that fails is retried once and then skipped, because
 * a wrong-shaped set is worse than a missing one.
 */

type Target = {
  level: "starters" | "movers" | "flyers";
  paper: "reading-writing";
  part: number;
  kind: ItemKind;
  count: number;
};

/**
 * Every Reading & Writing part that can be practised without illustration.
 * Question counts come from the real paper, via `syllabus.ts`.
 */
const TARGETS: Target[] = [
  { level: "starters", paper: "reading-writing", part: 3, kind: "spelling", count: 5 },
  { level: "starters", paper: "reading-writing", part: 4, kind: "word-box", count: 5 },

  { level: "movers", paper: "reading-writing", part: 2, kind: "dialogue-choice", count: 6 },
  { level: "movers", paper: "reading-writing", part: 3, kind: "word-box", count: 6 },
  { level: "movers", paper: "reading-writing", part: 4, kind: "option-gap", count: 5 },

  { level: "flyers", paper: "reading-writing", part: 1, kind: "definition", count: 10 },
  { level: "flyers", paper: "reading-writing", part: 2, kind: "dialogue-match", count: 5 },
  { level: "flyers", paper: "reading-writing", part: 3, kind: "word-box", count: 6 },
  { level: "flyers", paper: "reading-writing", part: 4, kind: "option-gap", count: 10 },
  { level: "flyers", paper: "reading-writing", part: 6, kind: "missing-word", count: 5 },
];

/** Varied so a batch is not twenty sets about the zoo. */
const TOPICS = [
  "animals and pets",
  "school and the classroom",
  "food and meals",
  "weather and the seasons",
  "sport and games",
  "holidays and travel",
  "the town and the shops",
  "family and home",
  "clothes and colours",
  "jobs people do",
  "the body and keeping well",
  "nature, trees and the sea",
];

const OUT = "content/yle-generated.ts";
const EXPORT_NAME = "GENERATED_SETS";

/**
 * The free tier allows five requests a minute. Pacing deliberately is far
 * better than discovering the limit through a 429 on every call: the retry in
 * gemini.ts would then wait out a full window each time, so an unpaced batch
 * is slower than a paced one as well as noisier.
 */
const PACE_MS = 13_000;
const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));

const args = process.argv.slice(2);
const eachFlag = args.indexOf("--each");
const EACH = eachFlag >= 0 ? Math.max(Number(args[eachFlag + 1]) || 2, 1) : 2;
const onlyLevels = args.filter((a) => !a.startsWith("--") && a !== String(EACH));

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
}

/** Reads back what is already generated, so a re-run adds rather than replaces. */
function existing(): PracticeSet[] {
  if (!existsSync(OUT)) return [];
  const src = readFileSync(OUT, "utf8");

  // Slice from the assignment, not from the first "[" — the first bracket in
  // the file belongs to the type annotation `PracticeSet[]`, so searching for
  // it parsed "[] = [...]" and threw. The catch below then silently started
  // fresh, discarding every set from the previous run.
  const marker = `${EXPORT_NAME}: PracticeSet[] = `;
  const at = src.indexOf(marker);
  if (at < 0) return [];

  try {
    return JSON.parse(src.slice(at + marker.length).replace(/;\s*$/, "")) as PracticeSet[];
  } catch (error) {
    // Loud, not silent: quietly starting fresh is how a run throws away work.
    console.error(`
Could not parse ${OUT}. Refusing to overwrite it.`);
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}

function write(sets: PracticeSet[]) {
  const header = `import type { PracticeSet } from "../src/lib/yle/items";

/**
 * GENERATED by \`npm run gen:yle\` — do not edit by hand.
 *
 * Every set here was produced by the real generator and passed the structural
 * checks in \`src/lib/yle/generate.ts\`: correct question count for the part,
 * exactly one correct option, gaps matching questions, answers present in the
 * word box. Structure being right does not make the English right, so these
 * still want a human read before anyone leans on them.
 *
 * Hand-authored sets live in \`yle-practice.ts\` and are never touched by the
 * generator.
 */
export const ${EXPORT_NAME}: PracticeSet[] = `;

  writeFileSync(OUT, header + JSON.stringify(sets, null, 2) + ";\n", "utf8");
}

async function main() {
  const targets = TARGETS.filter((t) => onlyLevels.length === 0 || onlyLevels.includes(t.level));
  const sets = existing();
  const titles = sets.map((s) => s.title);

  console.log(`\ngenerating ${EACH} set(s) for each of ${targets.length} part(s)\n`);

  let made = 0;
  let topicIndex = 0;

  for (const target of targets) {
    const level = levelBySlug(target.level)!;
    const paper = level.papers.find((p) => p.kind === target.paper)!;
    const part = paper.parts.find((p) => p.part === target.part)!;
    const label = `${level.name} R&W part ${target.part}`;

    for (let n = 0; n < EACH; n++) {
      const topic = TOPICS[topicIndex++ % TOPICS.length];

      if (made > 0 || topicIndex > 1) await wait(PACE_MS);

      // One retry: validation failures are usually a miscount the model fixes
      // when asked again, and a second failure means the part is a poor fit.
      let kept = false;
      for (let attempt = 1; attempt <= 2 && !kept; attempt++) {
        try {
          process.stdout.write(`  ...    ${label} — ${topic}`);
          const { set } = await generatePracticeSet({
            levelSlug: target.level,
            paper: target.paper,
            part: target.part,
            kind: target.kind,
            count: target.count,
            task: part.task,
            topicHint: topic,
            avoid: titles,
          });

          const id = `${target.level}-rw${target.part}-${slugify(set.title)}`;
          if (sets.some((s) => s.id === id)) {
            console.log(`\r  skip   ${label} — ${set.title} (already here)`);
            kept = true;
            break;
          }

          sets.push({ id, ...set });
          titles.push(set.title);
          made++;
          kept = true;
          console.log(`\r  ok     ${label} — ${set.title}`);
        } catch (error) {
          const message = error instanceof Error ? error.message : String(error);

          // A daily quota closes the door on the whole batch, not just this
          // set. Carrying on would burn minutes failing identically on every
          // remaining target, and bury the one line that explains why.
          if (/PerDay|per day/i.test(message)) {
            console.log(`\r  STOP   daily quota reached`);
            write(sets);
            console.error(
              `\n  The Gemini key has hit its per-day free-tier limit.\n` +
                `  ${made} set(s) generated and saved before stopping.\n` +
                `  Enable billing to continue, or re-run tomorrow.\n`,
            );
            process.exit(0);
          }

          if (attempt === 2) {
            console.log(`\r  FAIL   ${label} — ${topic}`);
            console.error(`         ${message}`);
          }
        }
      }

      // Written after every set, so an interrupted run keeps what it paid for.
      write(sets);
    }
  }

  console.log(`\n${made} new set(s); ${sets.length} generated in total`);
  console.log(`wrote ${OUT}\n`);
}

main();
